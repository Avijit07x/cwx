import { mkdir, stat, writeFile } from 'node:fs/promises';
import { dirname, join as joinPath } from 'node:path';
import { Logger, NodeIO, type Document } from '@gltf-transform/core';
import { ALL_EXTENSIONS } from '@gltf-transform/extensions';
import {
  dedup,
  flatten,
  instance,
  join,
  meshopt,
  palette,
  prune,
  textureCompress,
  weld,
} from '@gltf-transform/functions';
import { Mode, toktx } from '@gltf-transform/cli';
import { MeshoptDecoder, MeshoptEncoder, MeshoptSimplifier } from 'meshoptimizer';
import sharp from 'sharp';
import { MODEL, VARIANT_FILES } from '../src/bench/model.ts';
import { LODS, type LodSpec } from './lods.ts';
import {
  hoistInstanceScale,
  pruneBatches,
  revertColourShifts,
  simplifyToModelError,
  snapDirections,
} from './pipeline.ts';
import { collectStats } from './stats.ts';
import {
  exists,
  findKtx,
  formatMegabytes,
  publicPath,
  putOnPath,
  type KtxTool,
} from './toolchain.ts';

const DATA_SLOTS = /^(normalTexture|occlusionTexture|metallicRoughnessTexture)$/;
const INSTANCE_MIN = 2;
const UASTC_RDO_LAMBDA = 4;

async function encodeTextures(
  document: Document,
  spec: LodSpec,
  ktx: KtxTool | null,
): Promise<void> {
  const colour: [number, number] = [spec.colourTextureSize, spec.colourTextureSize];
  if (!ktx) {
    await document.transform(
      textureCompress({ encoder: sharp, targetFormat: 'webp', resize: colour }),
    );
    return;
  }
  const uastc = {
    encoder: sharp,
    mode: Mode.UASTC,
    rdo: true,
    rdoLambda: UASTC_RDO_LAMBDA,
    rdoMultithreading: false,
  };
  await document.transform(
    toktx({ ...uastc, slots: DATA_SLOTS, resize: [spec.dataTextureSize, spec.dataTextureSize] }),
  );
  await revertColourShifts(document, toktx({ encoder: sharp, mode: Mode.ETC1S, resize: colour }));
  await document.transform(toktx({ ...uastc, resize: colour }));
}

async function buildLod(io: NodeIO, spec: LodSpec, ktx: KtxTool | null): Promise<void> {
  const started = performance.now();
  const document = await io.read(publicPath(VARIANT_FILES.raw));
  document.setLogger(new Logger(Logger.Verbosity.WARN));
  document.getRoot().getAsset().copyright = MODEL.credit;
  await document.transform(
    dedup(),
    instance({ min: INSTANCE_MIN }),
    palette(),
    flatten(),
    join(),
    snapDirections(),
    weld(),
    simplifyToModelError(spec.simplifyError),
    dedup(),
    prune(),
  );
  await encodeTextures(document, spec, ktx);
  await document.transform(
    meshopt({ encoder: MeshoptEncoder }),
    hoistInstanceScale(),
    pruneBatches(),
    prune(),
  );
  const output = publicPath(VARIANT_FILES[spec.id]);
  await mkdir(dirname(output), { recursive: true });
  await io.write(output, document);
  const { size } = await stat(output);
  const stats = collectStats(document);
  const seconds = ((performance.now() - started) / 1000).toFixed(1);
  console.log(
    `${spec.id}: ${formatMegabytes(size)}, ${stats.triangles} triangles, ` +
      `${stats.drawCalls} draw calls (${stats.instancedDrawCalls} instanced), ` +
      `${stats.textures.length} textures (${seconds} s) → ${output}`,
  );
}

function attribution(): string {
  return [
    `# ${MODEL.title}, optimised levels of detail`,
    '',
    '`lod0.glb`, `lod1.glb` and `lod2.glb` are generated by `pnpm assets:optimize` from the Khronos glTF sample model below. See `docs/model-optimisation.md` for the pipeline and statistics.',
    '',
    `- Source: [KhronosGroup/glTF-Sample-Assets, Models/${MODEL.name}](${MODEL.page}), commit \`${MODEL.commit}\`.`,
    `- Licence: [${MODEL.licence}](${MODEL.licenceUrl}).`,
    `- Credit: ${MODEL.credit}.`,
    '- Changes: geometry simplified with meshoptimizer, repeated meshes turned into GPU instances, textures resized and re-encoded as KTX2 (Basis Universal), vertex data quantised and Meshopt-compressed with glTF-Transform. Each file carries the credit in its `asset.copyright` field.',
    '',
  ].join('\n');
}

async function main(): Promise<void> {
  if (!(await exists(publicPath(VARIANT_FILES.raw)))) {
    console.error(`Missing ${publicPath(VARIANT_FILES.raw)}. Run pnpm assets:fetch first.`);
    process.exitCode = 1;
    return;
  }
  const ktx = await findKtx();
  if (ktx) {
    putOnPath(ktx);
    console.log(`Textures: KTX2 with KTX-Software ${ktx.version} (${ktx.path})`);
  } else {
    console.log(
      'Textures: KTX-Software 4.4+ not found (run pnpm assets:fetch or set KTX_BIN); ' +
        'falling back to WebP.',
    );
  }
  if (process.env.KTX_BIN && ktx?.path !== process.env.KTX_BIN) {
    console.log(`KTX_BIN=${process.env.KTX_BIN} is not a working ktx 4.4+ binary; ignored.`);
  }
  await Promise.all([MeshoptDecoder.ready, MeshoptEncoder.ready, MeshoptSimplifier.ready]);
  const io = new NodeIO().registerExtensions(ALL_EXTENSIONS).registerDependencies({
    'meshopt.decoder': MeshoptDecoder,
    'meshopt.encoder': MeshoptEncoder,
  });
  for (const spec of LODS) await buildLod(io, spec, ktx);
  const readme = publicPath(joinPath('models', MODEL.slug, 'README.md'));
  await writeFile(readme, attribution());
  console.log(`Wrote ${readme}`);
}

await main();
